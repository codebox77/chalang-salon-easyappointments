<?php
/**
 * Writes /var/www/html/config.php from environment variables (called by docker-entrypoint.sh).
 *
 * Every value is written with var_export(), so quotes or backslashes in passwords cannot break the file.
 * *_FILE variants (e.g. DB_PASSWORD_FILE=/run/secrets/db_password) are supported for Docker secrets.
 */

function env_value(string $name, string $default = ''): string
{
    $file = getenv($name . '_FILE');

    if ($file !== false && $file !== '' && is_readable($file)) {
        return rtrim((string) file_get_contents($file), "\r\n");
    }

    $value = getenv($name);

    return $value === false ? $default : $value;
}

function env_bool(string $name, bool $default): bool
{
    $value = getenv($name);

    return $value === false ? $default : filter_var($value, FILTER_VALIDATE_BOOLEAN);
}

$base_url = rtrim(env_value('BASE_URL', 'http://localhost'), '/');

$required = ['DB_HOST' => env_value('DB_HOST'), 'DB_NAME' => env_value('DB_NAME'), 'DB_USERNAME' => env_value('DB_USERNAME')];

foreach ($required as $name => $value) {
    if ($value === '') {
        fwrite(STDERR, "crcr: environment variable $name is required.\n");
        exit(1);
    }
}

$constants = [
    'BASE_URL' => $base_url,
    'LANGUAGE' => env_value('LANGUAGE', 'korean'),
    'DEBUG_MODE' => env_bool('DEBUG_MODE', false),
    'DB_HOST' => $required['DB_HOST'],
    'DB_NAME' => $required['DB_NAME'],
    'DB_USERNAME' => $required['DB_USERNAME'],
    'DB_PASSWORD' => env_value('DB_PASSWORD'),
    'GOOGLE_SYNC_FEATURE' => env_bool('GOOGLE_SYNC_FEATURE', false),
    'GOOGLE_CLIENT_ID' => env_value('GOOGLE_CLIENT_ID'),
    'GOOGLE_CLIENT_SECRET' => env_value('GOOGLE_CLIENT_SECRET'),
    'KAKAO_JAVASCRIPT_KEY' => env_value('KAKAO_JAVASCRIPT_KEY'),
];

$code = "<?php\n// Generated by docker/render-config.php from environment variables. Do not edit inside the container.\n\nclass Config\n{\n";

foreach ($constants as $name => $value) {
    $code .= '    const ' . $name . ' = ' . var_export($value, true) . ";\n";
}

$code .= "}\n";

$target = '/var/www/html/config.php';

if (file_put_contents($target, $code) === false) {
    fwrite(STDERR, "crcr: could not write $target.\n");
    exit(1);
}

chmod($target, 0640);
@chown($target, 'root');
@chgrp($target, 'www-data');

echo "crcr: config.php written (BASE_URL=$base_url).\n";
